func TestFuncRanges(t *testing.T) {
	src := `package p

type S struct{}
type G[K comparable, V any] struct{}
type H[T any] struct{}

func Free() {}

func (s *S) Ptr() {
}

func (g G[K, V]) Multi() {}

func (h *H[T]) Single() {}
`
	file := filepath.Join(t.TempDir(), "p.go")
	if err := os.WriteFile(file, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	funcs := funcRanges(file)
	var names []string
	for _, f := range funcs {
		names = append(names, f.name)
	}
	want := []string{"Free", "(*S).Ptr", "(G).Multi", "(*H).Single"}
	if !reflect.DeepEqual(names, want) {
		t.Errorf("names = %q, want %q", names, want)
	}
	if got := enclosingFunc(funcs, 10); got != "(*S).Ptr" {
		t.Errorf("enclosingFunc(10) = %q", got)
	}
	if got := enclosingFunc(funcs, 3); got != "" {
		t.Errorf("enclosingFunc(3) = %q, want none", got)
	}
	if funcRanges(filepath.Join(t.TempDir(), "missing.go")) != nil {
		t.Error("missing file should yield nil")
	}
}

func TestIsGenerated(t *testing.T) {
	dir := t.TempDir()
	write := func(name, src string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	if !isGenerated(write("g.go", "// Code generated by stringer; DO NOT EDIT.\n\npackage p\n")) {
		t.Error("generated file not detected")
	}
	if isGenerated(write("n.go", "package p\n\n// Code generated by x; DO NOT EDIT.\n")) {
		t.Error("marker after package clause must not count")
	}
	if isGenerated(filepath.Join(dir, "missing.go")) {
		t.Error("missing file is not generated")
	}
}

func TestHeadTail(t *testing.T) {
	l := []string{"a", "b", "c", "d"}
	if got := head(l, 2); !reflect.DeepEqual(got, []string{"a", "b", "... 2 more line(s) omitted"}) {
		t.Errorf("head = %q", got)
	}
	if got := tail(l, 2); !reflect.DeepEqual(got, []string{"... 2 earlier line(s) omitted", "c", "d"}) {
		t.Errorf("tail = %q", got)
	}
	if got := head(l, 0); len(got) != 4 {
		t.Errorf("head(0) should not truncate")
	}
	if got := tail(l, 10); len(got) != 4 {
		t.Errorf("tail(10) should not truncate")
	}
	if splitLines("\n") != nil {
		t.Error("blank output should split to nil")
	}
}

// --- end-to-end: run the hook against throwaway modules ---

func newModule(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	files["go.mod"] = "module example.com/m\n\ngo 1.22\n"
	for name, src := range files {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func runHook(t *testing.T, cwd, file string, args ...string) (int, string) {
	t.Helper()
	in, _ := json.Marshal(map[string]any{
		"cwd":        cwd,
		"tool_name":  "Edit",
		"tool_input": map[string]string{"file_path": file},
	})
	var stderr bytes.Buffer
	code := run(args, bytes.NewReader(in), &stderr)
	return code, stderr.String()
}

const calc = `package calc

// Add returns a+b.
func Add(a, b int) int { return a + b }

// Sign reports the sign of n.
func Sign(n int) int {
	if n < 0 {
		return -1
	}
	if n == 0 {
		return 0
	}
	return 1
}
`

func TestEndToEndPass(t *testing.T) {
	root := newModule(t, map[string]string{
		"calc/calc.go": calc,
		"calc/calc_test.go": `package calc

import "testing"

func TestAll(t *testing.T) {
	if Add(1, 2) != 3 || Sign(-2) != -1 || Sign(0) != 0 || Sign(5) != 1 {
		t.Fatal("wrong")
	}
}
`,
	})
	code, out := runHook(t, root, "calc/calc.go") // relative path, resolved against cwd
	if code != exitOK {
		t.Fatalf("exit %d, want 0:\n%s", code, out)
	}
}

func TestEndToEndLowCoverage(t *testing.T) {
	root := newModule(t, map[string]string{
		"calc/calc.go": calc,
		"calc/calc_test.go": `package calc

import "testing"

func TestAdd(t *testing.T) {
	if Add(1, 2) != 3 {
		t.Fatal("wrong")
	}
}
`,
	})
	code, out := runHook(t, root, filepath.Join(root, "calc/calc.go"))
	if code != exitBlock {
		t.Fatalf("exit %d, want 2:\n%s", code, out)
	}
	for _, want := range []string{"## coverage", "is 16.7%", "calc.go:7-14 in Sign"} {
		if !strings.Contains(out, want) {
			t.Errorf("report missing %q:\n%s", want, out)
		}
	}

	// Same package passes with a lower bar.
	if code, out := runHook(t, root, filepath.Join(root, "calc/calc.go"), "-min", "10"); code != exitOK {
		t.Errorf("-min 10: exit %d:\n%s", code, out)
	}
}

func TestEndToEndFormatAndNoTests(t *testing.T) {
	ugly := "package calc\n\nfunc   Add(a,b int)int{return a+b}\n"
	root := newModule(t, map[string]string{"calc/calc.go": ugly})
	file := filepath.Join(root, "calc/calc.go")

	code, out := runHook(t, root, file)
	if code != exitBlock {
		t.Fatalf("exit %d, want 2:\n%s", code, out)
	}
	for _, want := range []string{"## gofmt", "not gofmt-formatted", "has no tests"} {
		if !strings.Contains(out, want) {
			t.Errorf("report missing %q:\n%s", want, out)
		}
	}

	// -fix rewrites the file and only notes it.
	code, out = runHook(t, root, file, "-fix")
	if code != exitBlock || !strings.Contains(out, "gofmt reformatted calc.go") || strings.Contains(out, "## gofmt") {
		t.Errorf("-fix: exit %d:\n%s", code, out)
	}
	got, _ := os.ReadFile(file)
	if string(got) == ugly {
		t.Error("-fix did not rewrite the file")
	}
}

func TestEndToEndFailingTestsAndSyntax(t *testing.T) {
	root := newModule(t, map[string]string{
		"calc/calc.go": calc,
		"calc/calc_test.go": `package calc

import "testing"

func TestBroken(t *testing.T) { t.Fatal("boom") }
`,
		"bad/bad.go": "package bad\n\nfunc {\n",
	})
	code, out := runHook(t, root, filepath.Join(root, "calc/calc_test.go"))
	if code != exitBlock || !strings.Contains(out, "## go test") || !strings.Contains(out, "boom") {
		t.Errorf("failing test: exit %d:\n%s", code, out)
	}

	code, out = runHook(t, root, filepath.Join(root, "bad/bad.go"))
	if code != exitBlock || !strings.Contains(out, "syntax error") {
		t.Errorf("syntax error: exit %d:\n%s", code, out)
	}
}

func TestEndToEndIgnored(t *testing.T) {
	root := newModule(t, map[string]string{
		"calc/calc.go":     calc, // untested, would fail coverage
		"calc/zz_gen.go":   "// Code generated by hand; DO NOT EDIT.\n\npackage calc\n",
		"cmd/tool/main.go": "package main\n\nfunc main() {}\n",
		"README.md":        "hi",
	})
	for _, f := range []string{"calc/zz_gen.go", "cmd/tool/main.go", "README.md", "calc/gone.go"} {
		if code, out := runHook(t, root, filepath.Join(root, f), "-skip", "cmd/..."); code != exitOK {
			t.Errorf("%s: exit %d, want 0:\n%s", f, code, out)
		}
	}
	// Outside any module.
	loose := filepath.Join(t.TempDir(), "x.go")
	_ = os.WriteFile(loose, []byte("package x\n"), 0o644)
	if code, _ := runHook(t, "/", loose); code != exitOK {
		t.Errorf("file outside a module: exit %d", code)
	}
	// Coverage disabled.
	if code, out := runHook(t, root, filepath.Join(root, "calc/calc.go"), "-min", "0"); code != exitOK {
		t.Errorf("-min 0: exit %d:\n%s", code, out)
	}
}

